-- ---------------------------------------------------------------------
-- 16. Lightweight audit trail for sensitive tables
-- ---------------------------------------------------------------------
CREATE TABLE yieldshield.audit_log (
    audit_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name   VARCHAR(60) NOT NULL,
    row_pk       TEXT NOT NULL,
    action       VARCHAR(10) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
    changed_by   TEXT NOT NULL DEFAULT current_user,
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    old_data     JSONB,
    new_data     JSONB
);

CREATE OR REPLACE FUNCTION yieldshield.fn_audit_trigger() RETURNS TRIGGER AS $$
DECLARE
    pk_val TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        pk_val := (row_to_json(OLD)::jsonb ->> TG_ARGV[0]);
        INSERT INTO yieldshield.audit_log(table_name, row_pk, action, old_data)
        VALUES (TG_TABLE_NAME, pk_val, TG_OP, row_to_json(OLD)::jsonb);
        RETURN OLD;
    ELSIF TG_OP = 'UPDATE' THEN
        pk_val := (row_to_json(NEW)::jsonb ->> TG_ARGV[0]);
        INSERT INTO yieldshield.audit_log(table_name, row_pk, action, old_data, new_data)
        VALUES (TG_TABLE_NAME, pk_val, TG_OP, row_to_json(OLD)::jsonb, row_to_json(NEW)::jsonb);
        RETURN NEW;
    ELSE
        pk_val := (row_to_json(NEW)::jsonb ->> TG_ARGV[0]);
        INSERT INTO yieldshield.audit_log(table_name, row_pk, action, new_data)
        VALUES (TG_TABLE_NAME, pk_val, TG_OP, row_to_json(NEW)::jsonb);
        RETURN NEW;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = yieldshield, pg_catalog;

-- Track changes on the accounts and farm data that matter most for accountability.
CREATE TRIGGER trg_audit_user_account
    AFTER INSERT OR UPDATE OR DELETE ON yieldshield.user_account
    FOR EACH ROW EXECUTE FUNCTION yieldshield.fn_audit_trigger('user_id');

CREATE TRIGGER trg_audit_farm_profile
    AFTER INSERT OR UPDATE OR DELETE ON yieldshield.farm_profile
    FOR EACH ROW EXECUTE FUNCTION yieldshield.fn_audit_trigger('farm_id');

CREATE TRIGGER trg_audit_production_record
    AFTER INSERT OR UPDATE OR DELETE ON yieldshield.production_record
    FOR EACH ROW EXECUTE FUNCTION yieldshield.fn_audit_trigger('production_id');

COMMIT;
